function serializeLike(raw,orig,out){
  const strs=v=>{const a=[];(function w(x){
    if(typeof x==='string')a.push(x);
    else if(Array.isArray(x))x.forEach(w);
    else if(x&&typeof x==='object')for(const k of Object.keys(x)){a.push(k);w(x[k]);}
  })(v);return a;};
  try{
    const A=strs(orig),B=strs(out);
    const spans=[];
    for(let i=0;i<raw.length;i++){
      if(raw[i]!=='"')continue;
      let j=i+1;
      while(j<raw.length&&raw[j]!=='"'){j+=raw[j]==='\\'?2:1;}
      spans.push([i,j+1]);i=j;
    }
    if(spans.length===A.length&&A.length===B.length&&spans.every(([s,e],k)=>JSON.parse(raw.slice(s,e))===A[k])){
      let res='',pos=0;
      spans.forEach(([s,e],k)=>{
        if(A[k]===B[k])return;
        res+=raw.slice(pos,s)+JSON.stringify(B[k]);pos=e;
      });
      return res+raw.slice(pos);
    }
  }catch{}
  const m=raw.match(/\n([ \t]+)\S/);
  let txt=JSON.stringify(out,null,m?m[1]:0);
  if(raw.includes('\r\n'))txt=txt.replace(/\r?\n/g,'\r\n');
  if(/\n\s*$/.test(raw))txt+=raw.includes('\r\n')?'\r\n':'\n';
  return txt;
}


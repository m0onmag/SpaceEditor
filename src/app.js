function validatePack(root){
  const isO=v=>!!v&&typeof v==='object'&&!Array.isArray(v);
  if(!isO(root))return false;
  let count=0;
  const walk=(arr,depth)=>{
    if(arr===undefined)return true;
    if(!Array.isArray(arr)||depth>40)return false;
    for(const o of arr){
      if(!isO(o)||++count>20000)return false;
      if(o.type==='command'){
        if(typeof o.name!=='string')return false;
        if(o.sequence!==undefined&&(!Array.isArray(o.sequence)||o.sequence.some(s=>typeof s!=='string')))return false;
      }else{
        if(o.name!==undefined&&typeof o.name!=='string')return false;
        if(!walk(o.children,depth+1))return false;
      }
    }
    return true;
  };
  return walk(root.children,0);
}


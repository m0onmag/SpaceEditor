function openDiffDlg(){
  const P={a:null,b:null};
  let R=null,filter='all',q='';
  const nm=c=>[...c.path,c.name].join(' / ');
  const tagKey={ch:'diffChanged',ad:'diffAdded',rm:'diffRemoved'};
  const N={a:'',b:''},coll=new Set();let shown=[];
  const ck=(k,x)=>nm(x.c)+'|'+k;
  const nmH=c=>(c.path.length?`<span class="df-p">${escHtml(c.path.join(' / '))} /</span>`:'')+`<span class="df-nm">${escHtml(c.name)}</span>`;
  function paintSlot(s){
    const o=P[s];
    $('df-n-'+s).textContent=o?N[s]:'-';
    $('df-m-'+s).textContent=o?tp('cmds',flat(o).size):t('diffDrop');
    $('df-s-'+s).classList.toggle('ok',!!o);
    $('df-swap').disabled=!(P.a||P.b);
  }
  function syncTg(){
    const tg=$('df-tg'),on=!!shown.length&&shown.every(([k,x])=>coll.has(ck(k,x)));
    tg.querySelector('span').textContent=t(on?'diffExpand':'diffCollapse');
  }
  const $=id=>ov.querySelector('#'+id);

  function flat(root){
    const out=new Map();
    (function walk(arr,path){
      for(const o of arr){
        if(o.type==='command'){
          const base=[...path,o.name].join('/');let k=base,n=1;
          while(out.has(k))k=base+'#'+(++n);
          out.set(k,{path:[...path],name:o.name,seq:o.sequence||[]});
        }else walk(o.children||[],[...path,o.name]);
      }
    })(root.children||[],[]);
    return out;
  }

  function lineDiff(a,b){
    const n=a.length,m=b.length,ops=[];
    if(n*m>4e5){
      for(let i=0;i<Math.max(n,m);i++){
        if(a[i]===b[i])ops.push({k:'same',s:a[i]});
        else{if(i<n)ops.push({k:'del',s:a[i]});if(i<m)ops.push({k:'add',s:b[i]});}
      }
      return ops;
    }
    const L=Array.from({length:n+1},()=>new Array(m+1).fill(0));
    for(let i=n-1;i>=0;i--)for(let j=m-1;j>=0;j--)L[i][j]=a[i]===b[j]?L[i+1][j+1]+1:Math.max(L[i+1][j],L[i][j+1]);
    let i=0,j=0;
    while(i<n&&j<m){
      if(a[i]===b[j]){ops.push({k:'same',s:a[i]});i++;j++;}
      else if(L[i+1][j]>=L[i][j+1])ops.push({k:'del',s:a[i++]});
      else ops.push({k:'add',s:b[j++]});
    }
    while(i<n)ops.push({k:'del',s:a[i++]});
    while(j<m)ops.push({k:'add',s:b[j++]});
    return ops;
  }

  function compare(){
    const A=flat(P.a),B=flat(P.b),r={ch:[],ad:[],rm:[],same:0};
    for(const [k,c] of A){
      const d=B.get(k);
      if(!d)r.rm.push({c});
      else if(c.seq.length!==d.seq.length||c.seq.some((s,i)=>s!==d.seq[i]))r.ch.push({c,ops:lineDiff(c.seq,d.seq)});
      else r.same++;
    }
    for(const [k,c] of B)if(!A.has(k))r.ad.push({c});
    return r;
  }

  function row(k,s){
    const i=s.indexOf(':'),ty=i>0?s.slice(0,i):s,v=i>0?s.slice(i+1):'';
    return `<div class="df-ln ${k}"><span class="df-sg">${k==='add'?'+':k==='del'?'−':''}</span><span class="df-ty">${escHtml(ty.replace(/^(Sound\.|Key\.|Launch\.|System\.|Lux\.)/,''))}</span><span class="df-v">${escHtml(v)}</span></div>`;
  }

  function card(kind,x,i){
    const ops=x.ops||x.c.seq.map(s=>({k:kind==='ad'?'add':'del',s}));
    const na=ops.filter(o=>o.k==='add').length,nd=ops.filter(o=>o.k==='del').length;
    return `<div class="df-c ${kind}${coll.has(ck(kind,x))?' off':''}" data-i="${i}" style="animation-delay:${Math.min(i,10)*35}ms"><div class="df-h"><span class="df-dot ${kind}"></span><span class="df-n">${nmH(x.c)}</span>${na?`<span class="df-cnt add">+${na}</span>`:''}${nd?`<span class="df-cnt del">−${nd}</span>`:''}<span class="df-tag ${kind}">${t(tagKey[kind])}</span>${ops.length?'<i class="ti ti-chevron-down df-chev" aria-hidden="true"></i>':''}</div>${ops.length?`<div class="df-bw"><div class="df-b">${ops.map(o=>row(o.k,o.s)).join('')}</div></div>`:''}</div>`;
  }

  function render(){
    const body=$('df-body');
    $('df-bar').style.display=R?'':'none';$('df-ratio').style.display=R?'':'none';
    if(!R){body.innerHTML=`<div class="df-empty"><i class="ti ti-scale" aria-hidden="true"></i><span>${t('diffReady')}</span></div>`;return;}
    const total=R.ch.length+R.ad.length+R.rm.length;
    const chips=$('df-chips');
    chips.innerHTML=[['all',total,'diffAll'],['ch',R.ch.length,'diffChanged'],['ad',R.ad.length,'diffAdded'],['rm',R.rm.length,'diffRemoved']]
      .map(([k,n,l])=>`<button class="df-chip ${k}${filter===k?' on':''}" data-f="${k}">${t(l)}<b>${n}</b></button>`).join('');
    chips.querySelectorAll('.df-chip').forEach(b=>b.onclick=()=>{filter=b.dataset.f;render();});
    $('df-same').textContent=t('diffSame')+': '+R.same;
    $('df-ratio').innerHTML=[['ch',R.ch.length],['ad',R.ad.length],['rm',R.rm.length],['same',R.same]].filter(r=>r[1]).map(([k,n])=>`<i class="${k}" style="flex-grow:${n}" title="${escHtml(t(k==='same'?'diffSame':tagKey[k]))}: ${n}"></i>`).join('');
    const hit=x=>!q||nm(x.c).toLowerCase().includes(q);
    const items=[];shown=items;
    for(const k of ['ch','ad','rm'])if(filter==='all'||filter===k)for(const x of R[k])if(hit(x))items.push([k,x]);
    if(!total)body.innerHTML=`<div class="df-empty"><i class="ti ti-check" aria-hidden="true"></i><span>${t('diffNoChanges')}</span></div>`;
    else if(!items.length)body.innerHTML=`<div class="df-empty"><i class="ti ti-search" aria-hidden="true"></i><span>${t('diffNone')}</span></div>`;
    else{
      body.innerHTML=items.map(([k,x],i)=>card(k,x,i)).join('');
      body.querySelectorAll('.df-c').forEach(c=>{
        if(!c.querySelector('.df-bw'))return;
        const h=c.querySelector('.df-h');h.classList.add('tgl');
        h.onclick=()=>{
          const [k,x]=items[+c.dataset.i],key=ck(k,x),off=!coll.has(key);
          if(off)coll.add(key);else coll.delete(key);
          c.classList.toggle('off',off);syncTg();
        };
      });
    }
    body.scrollTop=0;syncTg();
  }

  function setPack(s,obj,name){
    P[s]=obj;N[s]=name;paintSlot(s);
    R=P.a&&P.b?compare():null;
    render();
  }

  function take(s,data,name){
    try{
      const o=JSON.parse(data);
      if(!validatePack(o))throw new Error('bad pack');
      setPack(s,o,name);
    }catch(e){setMsg(t(e&&e.name==='SyntaxError'?'parseErr':'loadErr'),'alert-triangle');}
  }

  async function pick(s){
    const r=await api.openJson(t('dlgOpen'));
    if(r)take(s,r.data,r.path?r.path.split(/[\\/]/).pop():'pack.json');
  }

  async function drop(s,f){
    if(f.size>20*1024*1024){setMsg(t('loadErr'),'alert-triangle');return;}
    take(s,await f.text(),f.name);
  }

  const slot=s=>`<div class="df-slot" id="df-s-${s}"><span class="df-bd">${s.toUpperCase()}</span><div class="df-si"><b id="df-n-${s}">-</b><small id="df-m-${s}">${t('diffDrop')}</small></div><button class="btn btn-ghost btn-sm" id="df-l-${s}"><i class="ti ti-folder-open" aria-hidden="true"></i><span>${t('diffLoad')}</span></button></div>`;

  const ov=document.createElement('div');ov.className='overlay';
  ov.innerHTML=`
    <div class="modal df-modal">
      <div class="modal-hdr">
        <i class="ti ti-scale" aria-hidden="true"></i>
        <span class="modal-title">${t('diffT')}</span>
      </div>
      <div class="df-slots">${slot('a')}<button class="df-swap" id="df-swap" disabled title="${escHtml(t('diffSwap'))}"><i class="ti ti-arrows-diff" aria-hidden="true"></i></button>${slot('b')}</div>
      <div class="df-ratio" id="df-ratio" style="display:none"></div>
      <div class="df-bar" id="df-bar" style="display:none">
        <div class="df-chips" id="df-chips"></div>
        <span class="df-same" id="df-same"></span>
        <button class="df-tg" id="df-tg"><i class="ti ti-arrows-vertical" aria-hidden="true"></i><span></span></button>
        <input class="m-search df-q" id="df-q" placeholder="${escHtml(t('diffSearch'))}">
      </div>
      <div class="df-body" id="df-body"></div>
      <div class="modal-ftr">
        <button class="btn btn-primary" id="df-x">${t('close')}</button>
      </div>
    </div>
  `;
  document.body.appendChild(ov);
  const close=()=>{off();ov.remove();};
  const off=escClose(ov,close);

  ['a','b'].forEach(s=>{
    $('df-l-'+s).onclick=()=>pick(s);
    const el=$('df-s-'+s);
    el.addEventListener('dragover',e=>{if(e.dataTransfer.types.includes('Files')){e.preventDefault();el.classList.add('over');}});
    el.addEventListener('dragleave',()=>el.classList.remove('over'));
    el.addEventListener('drop',e=>{
      e.preventDefault();el.classList.remove('over');
      const f=[...e.dataTransfer.files].find(x=>/\.json$/i.test(x.name));
      if(f)drop(s,f);else setMsg(t('parseErr'),'alert-triangle');
    });
  });
  $('df-q').oninput=e=>{q=e.target.value.trim().toLowerCase();render();};
  $('df-x').onclick=close;
  $('df-swap').onclick=()=>{
    [P.a,P.b]=[P.b,P.a];[N.a,N.b]=[N.b,N.a];
    paintSlot('a');paintSlot('b');
    R=P.a&&P.b?compare():null;render();
  };
  $('df-tg').onclick=()=>{
    const on=!!shown.length&&shown.every(([k,x])=>coll.has(ck(k,x)));
    shown.forEach(([k,x])=>on?coll.delete(ck(k,x)):coll.add(ck(k,x)));
    $('df-body').querySelectorAll('.df-c').forEach(c=>c.classList.toggle('off',!on&&!!c.querySelector('.df-bw')));
    syncTg();
  };
  render();
}


function openApplyAll(){
  if(!cmds.length)return;
  let sel=new Set(),filterQ='';

  function buildList(){
    const groups={},order=[];
    for(const v of voices){
      if(filterQ&&!v.name.toLowerCase().includes(filterQ)&&!v.category.toLowerCase().includes(filterQ))continue;
      if(!groups[v.category]){groups[v.category]=[];order.push(v.category);}
      groups[v.category].push(v);
    }
    const n=sel.size;
    document.getElementById('aa-cnt').textContent=n?t('selN',{f:tp('files',n)}):t('selNone');
    document.getElementById('aa-ok').disabled=n===0;
    const listEl=document.getElementById('aa-list');listEl.innerHTML='';
    for(const cat of order){
      const catVoices=groups[cat];
      const allSel=catVoices.every(v=>sel.has(v.name));
      const lbl=document.createElement('div');
      lbl.className='v-cat has-btn';
      lbl.innerHTML=`<span>${escHtml(cat)}</span><button class="btn btn-ghost btn-sm aa-cat-btn"><i class="ti ti-${allSel?'x':'check'}" aria-hidden="true"></i><span>${allSel?t('catNone'):t('catAll')}</span></button>`;
      lbl.querySelector('.aa-cat-btn').onclick=e=>{
        e.stopPropagation();
        const all=catVoices.every(v=>sel.has(v.name));
        catVoices.forEach(v=>all?sel.delete(v.name):sel.add(v.name));
        buildList();
      };
      listEl.appendChild(lbl);
      for(const v of catVoices){
        const c=sel.has(v.name);
        const el=document.createElement('div');
        el.className='v-item'+(c?' sel':'');
        el.innerHTML=`<div class="chk${c?' on':''}"><i class="ti ti-check" aria-hidden="true"></i></div><span class="v-label">${escHtml(v.name.replace(/\.wav$/i,''))}</span>`;
        el.onclick=()=>{if(sel.has(v.name))sel.delete(v.name);else sel.add(v.name);buildList();};
        listEl.appendChild(el);
      }
    }
  }

  const ov=document.createElement('div');ov.className='overlay';
  ov.innerHTML=`
    <div class="modal" style="width:500px;height:min(640px,84vh)">
      <div class="modal-hdr">
        <i class="ti ti-bolt" aria-hidden="true"></i>
        <span class="modal-title">${t('apply')}</span>
      </div>
      <div class="modal-body">
        <div class="desc-text">${t('aaDesc')}</div>
        <input class="m-search" placeholder="${escHtml(t('filterPh'))}" id="aa-search">
        <div class="voice-count" id="aa-cnt">${t('selNone')}</div>
        <div id="aa-list" style="overflow-y:auto;flex:1;min-height:0"></div>
      </div>
      <div class="modal-ftr">
        <button class="btn btn-ghost" id="aa-cancel">${t('cancel')}</button>
        <button class="btn btn-primary" id="aa-ok" disabled><i class="ti ti-bolt" aria-hidden="true"></i> ${t('apply')}</button>
      </div>
    </div>
  `;
  document.body.appendChild(ov);
  document.getElementById('aa-search').oninput=e=>{filterQ=e.target.value.toLowerCase();buildList();};
  document.getElementById('aa-cancel').onclick=()=>ov.remove();
  document.getElementById('aa-ok').onclick=async()=>{
    if(!sel.size)return;
    const files=[...sel];
    const label=files.length===1?files[0].replace(/\.wav$/i,''):tp('files',files.length);
    if((!window.VS||VS.confirmAll)&&!await askConfirm(t('aaConfirmT'),t('aaConfirm',{l:label}),t('applyBtn')))return;
    let cnt=0,ci=0;
    function walk(arr){for(const o of arr){if(o.type==='command'){(o.sequence||[]).forEach((s,si)=>{if(s.startsWith('Sound.PlayWav:')){if(!asgn[ci])asgn[ci]={};asgn[ci][si]={files,isRandom:true};cnt++;}});ci++;}else walk(o.children||[]);}}
    walk(rootObj.children||[]);dirty=true;
    ov.remove();if(selIdx>=0)renderEditor();rebuildSidebar();updateStats();
    setMsg(t('aaDone',{n:cnt,l:label}),'bolt');
  };
  buildList();
}

function updateStats(){
  document.getElementById('stat-cmds').textContent=t('statCmds',{n:cmds.length});
  let v=0;for(const sm of Object.values(asgn))if(Object.values(sm).some(a=>a.files&&a.files.length))v++;
  document.getElementById('stat-voiced').textContent=t('statVoiced',{n:v});
  const used=new Set();for(const sm of Object.values(asgn))for(const a of Object.values(sm))(a.files||[]).forEach(f=>used.add(f));
  document.getElementById('stat-files').textContent=t('statFiles',{n:used.size});
}


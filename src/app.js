function recSanitize(a){
  const out={};
  if(!a||typeof a!=='object'||Array.isArray(a))return out;
  for(const [ci,sm] of Object.entries(a)){
    const i=+ci;
    if(!Number.isInteger(i)||i<0||i>=cmds.length||!sm||typeof sm!=='object')continue;
    const o={};
    for(const [si,v] of Object.entries(sm)){
      const j=+si;
      if(!Number.isInteger(j)||j<0||!v||!Array.isArray(v.files))continue;
      const files=v.files.filter(f=>typeof f==='string').slice(0,500);
      if(files.length)o[j]={files,isRandom:!!v.isRandom};
    }
    if(Object.keys(o).length)out[i]=o;
  }
  return out;
}
